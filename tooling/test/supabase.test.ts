// Supabase scaffold checks (Req 9.1, 9.2, 9.3, 9.4, 9.6, 9.7).
// Parses `supabase/config.toml` with smol-toml and checks the trimmed `supabase init` output:
// the pinned top-level table set, the project id, the header line, secret-bearing settings,
// the placeholder seed file and the absence of any SQL statements or migrations.

import { readdirSync, readFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "smol-toml";
import { describe, expect, it } from "vitest";

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const SUPABASE_DIR = join(ROOT, "supabase");
const CONFIG_PATH = join(SUPABASE_DIR, "config.toml");

/** Supabase CLI version used for the one-off `supabase init`. */
const CLI_VERSION = "2.120.0";

/** Top-level tables in the file generated by Supabase CLI 2.120.0 (sorted). */
const EXPECTED_TOP_LEVEL_TABLES = [
  "analytics",
  "api",
  "auth",
  "db",
  "edge_runtime",
  "experimental",
  "local_smtp",
  "realtime",
  "storage",
  "studio",
];

/** Directories the CLI writes local state into; never part of the scaffold. */
const EXCLUDED_DIRS = new Set([".temp", ".branches"]);

const SECRET_LIKE_KEY = /secret|password|pass|token|api_key|auth_token|key$/i;
const ENV_REFERENCE = /^env\([A-Z0-9_]+\)$/;
const SQL_STATEMENT = /^\s*(create|alter|drop|insert|update|delete|grant|revoke|truncate)\b/i;

type TomlTable = Record<string, unknown>;

function isTable(value: unknown): value is TomlTable {
  return (
    typeof value === "object" && value !== null && !Array.isArray(value) && !(value instanceof Date)
  );
}

function readText(path: string): string {
  return readFileSync(path, "utf8").replace(/\r\n/g, "\n");
}

function toRepoPath(abs: string): string {
  return relative(ROOT, abs).split(sep).join("/");
}

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const abs = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!EXCLUDED_DIRS.has(entry.name)) out.push(...walk(abs));
    } else if (entry.isFile()) {
      out.push(abs);
    }
  }
  return out;
}

type KeyMatch = { path: string; value: unknown };

/** Recursively collects every key whose name looks secret-bearing, with its dotted path. */
function collectSecretLikeKeys(node: unknown, prefix: string): KeyMatch[] {
  if (Array.isArray(node)) {
    return node.flatMap((item, index) => collectSecretLikeKeys(item, `${prefix}[${index}]`));
  }
  if (!isTable(node)) return [];
  return Object.entries(node).flatMap(([key, value]) => {
    const path = prefix === "" ? key : `${prefix}.${key}`;
    const own = SECRET_LIKE_KEY.test(key) ? [{ path, value }] : [];
    return [...own, ...collectSecretLikeKeys(value, path)];
  });
}

describe("supabase scaffold", () => {
  const configText = readText(CONFIG_PATH);
  const config = parse(configText) as TomlTable;

  it("config.toml line 1 names the Supabase CLI version used for init", () => {
    expect(configText.split("\n")[0]).toBe(
      `# Generated by Supabase CLI ${CLI_VERSION} (supabase init).`,
    );
  });

  it("config.toml has exactly the pinned top-level tables plus project_id", () => {
    const keys = Object.keys(config);
    const tables = keys.filter((key) => isTable(config[key])).sort();
    const scalars = keys.filter((key) => !isTable(config[key])).sort();
    expect(tables).toEqual(EXPECTED_TOP_LEVEL_TABLES);
    expect(scalars).toEqual(["project_id"]);
    expect(config["project_id"]).toBe("xelulu");
  });

  it("secret-like string settings are empty or env(NAME) references", () => {
    const matches = collectSecretLikeKeys(config, "");
    // Non-string values (booleans like enable_refresh_token_rotation, numbers like
    // minimum_password_length) can't hold a credential, so only strings are asserted.
    const strings = matches.filter((m) => typeof m.value === "string");
    const nonStrings = matches.filter((m) => typeof m.value !== "string");
    for (const m of nonStrings) {
      expect(["boolean", "number", "bigint"], `${m.path} has an unexpected value type`).toContain(
        typeof m.value,
      );
    }
    expect(strings.length).toBeGreaterThan(0);

    // Report paths only, never values.
    const offending = strings
      .filter((m) => m.value !== "" && !ENV_REFERENCE.test(m.value as string))
      .map((m) => m.path);
    expect(
      offending,
      `Secret-like settings must be "" or env(NAME):\n${offending.join("\n")}`,
    ).toEqual([]);
  });

  it("seed.sql holds exactly one -- comment line plus blank lines", () => {
    const lines = readText(join(SUPABASE_DIR, "seed.sql")).split("\n");
    const nonBlank = lines.filter((line) => line.trim() !== "");
    expect(nonBlank).toHaveLength(1);
    expect(nonBlank[0]?.startsWith("--")).toBe(true);
  });

  it("no file under supabase/ contains SQL statements", () => {
    const files = walk(SUPABASE_DIR);
    expect(files.map(toRepoPath)).toEqual(
      expect.arrayContaining(["supabase/config.toml", "supabase/seed.sql"]),
    );
    const findings = files.flatMap((abs) =>
      readText(abs)
        .split("\n")
        .map((line, index) => ({ line, lineNo: index + 1 }))
        .filter(({ line }) => !line.trimStart().startsWith("--") && SQL_STATEMENT.test(line))
        .map(({ lineNo }) => `${toRepoPath(abs)}:${lineNo}`),
    );
    expect(findings, `SQL statements found:\n${findings.join("\n")}`).toEqual([]);
  });

  it("supabase/migrations holds only .gitkeep", () => {
    expect(readdirSync(join(SUPABASE_DIR, "migrations")).sort()).toEqual([".gitkeep"]);
  });
});
